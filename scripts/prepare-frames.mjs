import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const ROOT_DIR = process.cwd();
const SOURCE_DIR = path.join(ROOT_DIR, 'my-frames');
const DEST_DESKTOP = path.join(ROOT_DIR, 'public', 'frames', 'desktop');
const DEST_MOBILE = path.join(ROOT_DIR, 'public', 'frames', 'mobile');
const CONFIG_FILE = path.join(ROOT_DIR, 'content', 'intro-frames.js');

async function prepareFrames() {
  console.log('--- Preparing Moon Light Resort Intro Frames ---');

  if (!fs.existsSync(SOURCE_DIR)) {
    console.error(`Error: Source directory "${SOURCE_DIR}" does not exist.`);
    process.exit(1);
  }

  // Ensure destinations exist
  fs.mkdirSync(DEST_DESKTOP, { recursive: true });
  fs.mkdirSync(DEST_MOBILE, { recursive: true });
  fs.mkdirSync(path.dirname(CONFIG_FILE), { recursive: true });

  // Get all valid image files in my-frames
  const supportedExtensions = ['.webp', '.jpg', '.jpeg', '.png'];
  const files = fs.readdirSync(SOURCE_DIR)
    .filter((f) => supportedExtensions.includes(path.extname(f).toLowerCase()))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));

  if (files.length === 0) {
    console.error(`Error: No image frames found in ${SOURCE_DIR}`);
    process.exit(1);
  }

  if (files.length < 100) {
    console.error(`Error: Found ${files.length} frames. Intro requires at least 100 frames (target ~120).`);
    process.exit(1);
  }

  console.log(`Found ${files.length} frames in ${SOURCE_DIR}. Processing...`);

  let desktopTotalBytes = 0;
  let mobileTotalBytes = 0;

  for (let i = 0; i < files.length; i++) {
    const srcFile = path.join(SOURCE_DIR, files[i]);
    const frameIndex = String(i + 1).padStart(3, '0');
    const outDesktopFile = path.join(DEST_DESKTOP, `${frameIndex}.webp`);
    const outMobileFile = path.join(DEST_MOBILE, `${frameIndex}.webp`);

    // Desktop: 1920x1080 WebP q80
    await sharp(srcFile)
      .resize({ width: 1920, height: 1080, fit: 'cover' })
      .webp({ quality: 80, effort: 4 })
      .toFile(outDesktopFile);

    const dStat = fs.statSync(outDesktopFile);
    desktopTotalBytes += dStat.size;

    // Mobile: 1280x720 WebP q70
    await sharp(srcFile)
      .resize({ width: 1280, height: 720, fit: 'cover' })
      .webp({ quality: 70, effort: 4 })
      .toFile(outMobileFile);

    const mStat = fs.statSync(outMobileFile);
    mobileTotalBytes += mStat.size;

    if ((i + 1) % 20 === 0 || i + 1 === files.length) {
      console.log(`Processed ${i + 1}/${files.length} frames...`);
    }
  }

  const desktopMB = (desktopTotalBytes / (1024 * 1024)).toFixed(2);
  const mobileMB = (mobileTotalBytes / (1024 * 1024)).toFixed(2);

  console.log(`✓ Desktop frames: ${files.length} files (${desktopMB} MB, target <= 30 MB)`);
  console.log(`✓ Mobile frames: ${files.length} files (${mobileMB} MB, target <= 12 MB)`);

  // Write content/intro-frames.js config
  const configContent = `// AUTO-GENERATED BY scripts/prepare-frames.mjs - DO NOT EDIT MANUALLY
export const introFramesConfig = {
  frameCount: ${files.length},
  desktopDir: '/frames/desktop',
  mobileDir: '/frames/mobile',
  filePattern: '%03d.webp',
  extension: 'webp',
  desktopSizeMB: ${desktopMB},
  mobileSizeMB: ${mobileMB},
};
`;

  fs.writeFileSync(CONFIG_FILE, configContent, 'utf-8');
  console.log(`✓ Updated config in ${CONFIG_FILE}`);
  console.log('--- Frames preparation complete! ---');
}

prepareFrames().catch((err) => {
  console.error('Fatal error preparing frames:', err);
  process.exit(1);
});
